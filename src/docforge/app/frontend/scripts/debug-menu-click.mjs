import { chromium } from 'playwright';
const BASE = 'http://localhost:10046';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 375, height: 900 } });
const page = await ctx.newPage();
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
const menuBtn = page.locator('button[aria-label="Open navigation menu"]');
console.log('menuBtn count', await menuBtn.count());
await menuBtn.click();
await page.waitForTimeout(300);
const nav = page.locator('.df-topbar-nav--open');
console.log('nav open count', await nav.count());
const workersBtn = nav.getByText('Workers', { exact: true });
console.log('workersBtn count', await workersBtn.count());
const box = await workersBtn.boundingBox();
console.log('workersBtn box', box);
await workersBtn.click({ timeout: 5000 });
await page.waitForTimeout(800);
const h1 = await page.locator('h1').first().innerText().catch(() => 'NO H1');
console.log('h1 after click', h1);
await page.screenshot({ path: '/work/debug-after-click.png' });
await browser.close();
